-- =====================================================================
-- 「導入前在庫」→「旧原価在庫」への変更（1回だけ実行）
-- ・すでにある在庫のメモに入っている「導入前在庫」を「旧原価在庫」に置き換えます
--   例：「導入前在庫（原価は P2026…の便から）」→「旧原価在庫（原価は P2026…の便から）」
-- ・数量・原価・在庫金額は変わりません
-- 先に入庫一括の supabase/cost_lots.sql（更新版）を実行してから、このファイルを実行してください
-- （これから作られる在庫のメモも「旧原価在庫」になります）。
-- もう一度実行しても結果は変わりません。
-- =====================================================================

update public.cost_lots
   set note = replace(note, '導入前在庫', '旧原価在庫')
 where note like '%導入前在庫%';

-- 確認：残っていなければ 0
select count(*) as remaining from public.cost_lots where note like '%導入前在庫%';
