-- =====================================================================
-- 「期首在庫」→「導入前在庫」への変更（1回だけ実行）
-- ・登録日を 2000-01-01 にそろえる（在庫一覧で便より下に並べ、「いちばん新しい在庫の原価」で便を優先するため）
-- ・メモの「期首在庫」を「導入前在庫」に置き換える
-- NEから取ってきた日は created_at に残っているので、画面にはそちらを「取得日」として表示します。
-- 先に入庫一括の supabase/cost_lots.sql（更新版）を実行してから、このファイルを実行してください。
-- もう一度実行しても結果は変わりません。
-- =====================================================================

update public.cost_lots
   set received_at = timestamptz '2000-01-01 00:00:00+09'
 where lot_type = 'opening'
   and received_at <> timestamptz '2000-01-01 00:00:00+09';

update public.cost_lots
   set note = replace(note, '期首在庫', '導入前在庫')
 where note like '%期首在庫%';
